import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const REPOSITORY_ROOT = fileURLToPath(new URL("../", import.meta.url));
const BACKEND_CONFIG_PATH = new URL("home/game-stats-backend.js", import.meta.url);
const HOME_ENTRY_PATH = new URL("../home.html", import.meta.url);
const INDEX_ENTRY_PATH = new URL("../index.html", import.meta.url);
const WRANGLER_CONFIG_PATH = new URL("../workers/game-stats/wrangler.jsonc", import.meta.url);
const WRANGLER_CONFIG_EXAMPLE_PATH = new URL(
  "../workers/game-stats/wrangler.jsonc.example",
  import.meta.url
);

/**
 * These are the browser files that decide when a game starts and completes.
 * The digest is a release identifier, not a secret or proof that a client did
 * not modify code after the browser loaded it.
 */
export const GAME_COMPLETION_SOURCE_FILES = Object.freeze([
  "scripts/home/main.js",
  "scripts/home/core/dom.js",
]);

const INTEGRITY_CACHE_ASSET_PATHS = Object.freeze([
  "scripts/home/game-stats-backend.js",
  "scripts/home/core/dom.js",
  "scripts/home/main.js",
]);

const toRepositoryUrl = (relativePath) => new URL(relativePath, `file://${REPOSITORY_ROOT}`);

const readConfiguredApiBaseUrl = async () => {
  try {
    const config = await readFile(BACKEND_CONFIG_PATH, "utf8");
    return config.match(/apiBaseUrl:\s*"([^"]*)"/)?.[1] || "";
  } catch (error) {
    if (error?.code === "ENOENT") return "";
    throw error;
  }
};

export const calculateGameBuildVersion = async () => {
  const digest = createHash("sha256");
  for (const relativePath of GAME_COMPLETION_SOURCE_FILES) {
    digest.update(relativePath);
    digest.update("\0");
    digest.update(await readFile(toRepositoryUrl(relativePath)));
    digest.update("\0");
  }
  return `sha256-${digest.digest("hex")}`;
};

const createFrontendConfig = (apiBaseUrl, buildVersion) => `// Generated by scripts/update-game-integrity.mjs. Do not edit the buildVersion by hand.\n// apiBaseUrl is public configuration; leave it empty until the Worker has a live route.\nwindow.rohinGameStatsBackend = Object.freeze({\n  apiBaseUrl: ${JSON.stringify(apiBaseUrl)},\n  buildVersion: ${JSON.stringify(buildVersion)},\n});\n`;

const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const createIntegrityCacheToken = (buildVersion) =>
  `game-build-${buildVersion.replace(/^sha256-/, "")}`;

const updateIntegrityCacheReferences = (source, cacheToken) =>
  INTEGRITY_CACHE_ASSET_PATHS.reduce((updatedSource, assetPath) => {
    const referencePattern = new RegExp(
      `(${escapeRegExp(assetPath)}\\?v=)[^"\\]\\s]+`,
      "g"
    );
    const referenceFound = referencePattern.test(updatedSource);
    referencePattern.lastIndex = 0;
    const nextSource = updatedSource.replace(referencePattern, `$1${cacheToken}`);
    if (!referenceFound) {
      throw new Error(`Missing integrity cache reference for ${assetPath}`);
    }
    return nextSource;
  }, source);

const updateWranglerBuildVersion = (source, buildVersion) => {
  const config = JSON.parse(source);
  config.vars = { ...config.vars, GAME_BUILD_VERSION: buildVersion };
  return `${JSON.stringify(config, null, 2)}\n`;
};

const fileMatches = async (path, expected) => {
  try {
    return (await readFile(path, "utf8")) === expected;
  } catch (error) {
    if (error?.code === "ENOENT") return false;
    throw error;
  }
};

export const updateGameIntegrity = async ({ check = false } = {}) => {
  const buildVersion = await calculateGameBuildVersion();
  const apiBaseUrl = await readConfiguredApiBaseUrl();
  const frontendConfig = createFrontendConfig(apiBaseUrl, buildVersion);
  const wranglerConfig = updateWranglerBuildVersion(
    await readFile(WRANGLER_CONFIG_PATH, "utf8"),
    buildVersion
  );
  const wranglerConfigExample = updateWranglerBuildVersion(
    await readFile(WRANGLER_CONFIG_EXAMPLE_PATH, "utf8"),
    buildVersion
  );
  const cacheToken = createIntegrityCacheToken(buildVersion);
  const [homeEntry, indexEntry] = await Promise.all([
    readFile(HOME_ENTRY_PATH, "utf8"),
    readFile(INDEX_ENTRY_PATH, "utf8"),
  ]);

  const expectedFiles = [
    [BACKEND_CONFIG_PATH, frontendConfig],
    [HOME_ENTRY_PATH, updateIntegrityCacheReferences(homeEntry, cacheToken)],
    [INDEX_ENTRY_PATH, updateIntegrityCacheReferences(indexEntry, cacheToken)],
    [WRANGLER_CONFIG_PATH, wranglerConfig],
    [WRANGLER_CONFIG_EXAMPLE_PATH, wranglerConfigExample],
  ];
  const allCurrent = (await Promise.all(expectedFiles.map(([path, value]) => fileMatches(path, value)))).every(
    Boolean
  );

  if (check) {
    if (!allCurrent) {
      throw new Error(
        "Game integrity metadata is stale. Run: node scripts/update-game-integrity.mjs"
      );
    }
    return buildVersion;
  }

  await Promise.all(expectedFiles.map(([path, value]) => writeFile(path, value)));
  return buildVersion;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.slice(2).includes("--check");
  const buildVersion = await updateGameIntegrity({ check });
  console.log(`${check ? "Verified" : "Updated"} game build version: ${buildVersion}`);
}
